impl Appearance {
    /// Texture asset name for this look (generated by the renderer).
    pub fn texture_name(&self) -> String {
        use std::hash::{Hash, Hasher};
        let mut h = std::collections::hash_map::DefaultHasher::new();
        self.hash(&mut h);
        format!("__farmer/{:016x}", h.finish())
    }
}

#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash, Serialize, Deserialize, PartialOrd, Ord)]
pub enum Skill {
    Farming,
    Fishing,
    Foraging,
    Mining,
    Combat,
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Skills {
    pub xp: BTreeMap<Skill, i32>,
}

impl Skills {
    pub fn xp(&self, s: Skill) -> i32 {
        *self.xp.get(&s).unwrap_or(&0)
    }
    pub fn level(&self, s: Skill) -> i32 {
        let xp = self.xp(s);
        XP_LEVELS.iter().take_while(|&&t| xp >= t).count() as i32
    }
    /// Add experience; returns the new level if it increased.
    pub fn gain(&mut self, s: Skill, amount: i32) -> Option<i32> {
        let before = self.level(s);
        *self.xp.entry(s).or_insert(0) += amount.max(0);
        let after = self.level(s);
        (after > before).then_some(after)
    }
}

#[derive(Clone, Debug, Default, PartialEq, Serialize, Deserialize)]
pub struct Friendship {
    pub points: i32,
    pub talked_today: bool,
    pub gifts_this_week: i32,
    pub gifted_today: bool,
    pub met: bool,
    #[serde(default)]
    pub status: RelationStatus,
}

#[derive(Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize)]
pub enum RelationStatus {
    #[default]
    Friendly,
    Dating,
    /// Wedding happens on this `days_played` value.
    Engaged { wedding_day: i32 },
    Married,
}

impl Friendship {
    pub const POINTS_PER_HEART: i32 = 250;
    pub fn hearts(&self) -> i32 {
        self.points / Self::POINTS_PER_HEART
    }

    /// Maximum friendship points for the current relationship (documented
    /// caps: 8 hearts for romanceable villagers until dating, 10 while
    /// dating, 14 when married).
    pub fn max_points(&self, romanceable: bool) -> i32 {
        match self.status {
            RelationStatus::Married => 14 * Self::POINTS_PER_HEART,
            RelationStatus::Dating | RelationStatus::Engaged { .. } => 10 * Self::POINTS_PER_HEART,
            RelationStatus::Friendly if romanceable => 8 * Self::POINTS_PER_HEART,
            RelationStatus::Friendly => 10 * Self::POINTS_PER_HEART,
        }
    }
}

/// In-progress tool swing.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ToolUse {
    pub kind: ToolKind,
    pub slot: usize,
    pub target: TilePos,
    pub elapsed_ms: u32,
    pub applied: bool,
    /// Charge level for area tools (0 = single tile).
    #[serde(default)]
    pub power: i32,
}

/// Holding the button with an upgraded hoe / watering can.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct ToolCharge {
    pub kind: ToolKind,
    pub slot: usize,
    pub max_power: i32,
    pub ms: u32,
}

/// Milliseconds of holding per charge level (approximation).
pub const CHARGE_STEP_MS: u32 = 600;

impl ToolCharge {
    pub fn power(&self) -> i32 {
        ((self.ms / CHARGE_STEP_MS) as i32).min(self.max_power)
    }
}

/// Tool swing timing (approximate): effect lands at HIT, swing ends at TOTAL.
pub const TOOL_HIT_MS: u32 = 200;
pub const TOOL_TOTAL_MS: u32 = 400;

